<#
uninstall-officeapps.ps1: removes App Updater and the apps it installed.
Generated by updpublish. Run it as SYSTEM (RMM) or from an elevated Windows
PowerShell 5.1 or later. It never prompts.

  -KeepApps    remove only App Updater; leave the apps installed

It deletes the scheduled tasks first (so nothing reinstalls an app), then
uninstalls the apps silently, then removes the updater's folders and its
Uninstall registry entry.

Exit codes: 0 everything removed; 1 something was left behind (or not
elevated). Each leftover is listed.
#>
[CmdletBinding()]
param(
    [switch]$KeepApps
)

Set-StrictMode -Version 2
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$Tasks = @('AppUpdater', 'AppUpdater-Logon')
$UpdaterKey = 'SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\AppUpdater'
$Apps = @(
    @{ Id = 'pdf-reader'; Name = 'PDF Reader'; Match = 'SumatraPDF'; Args = @('-s') },
    @{ Id = 'office-suite'; Name = 'Documents and Spreadsheets'; Match = 'LibreOffice'; Args = @() },
    @{ Id = 'photo-album'; Name = 'Photo Album'; Match = 'Photo Album'; Args = @('/S') }
)

function Write-Log([string]$Message) {
    Write-Output ((Get-Date).ToString('yyyy-MM-dd HH:mm:ss') + ' ' + $Message)
}

# Runs a program with an argument array (never a built command string) and
# leaves its exit code in $script:NativeExit. -Quiet drops its output.
function Invoke-Native([string]$Exe, [string[]]$Arguments, [switch]$Quiet) {
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        if ($Quiet) {
            & $Exe @Arguments 2>&1 | Out-Null
        } else {
            & $Exe @Arguments 2>&1 | ForEach-Object { Write-Log ('  ' + [string]$_) }
        }
        $script:NativeExit = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $old
    }
}

if ([IntPtr]::Size -eq 4 -and $env:PROCESSOR_ARCHITEW6432) {
    $native = Join-Path $env:SystemRoot 'Sysnative\WindowsPowerShell\v1.0\powershell.exe'
    if ((Test-Path -LiteralPath $native) -and $PSCommandPath) {
        $fwd = @('-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', $PSCommandPath)
        if ($KeepApps) { $fwd += '-KeepApps' }
        Write-Log 'restarting in 64-bit PowerShell'
        Invoke-Native $native $fwd
        exit $script:NativeExit
    }
}

$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Log 'ERROR: run this as SYSTEM or from an elevated PowerShell (Run as administrator).'
    exit 1
}

$schtasks = Join-Path $env:SystemRoot 'System32\schtasks.exe'
$msiexec = Join-Path $env:SystemRoot 'System32\msiexec.exe'
$programDir = Join-Path $env:ProgramFiles 'AppUpdater'
$dataDir = Join-Path $env:ProgramData 'AppUpdater'

# Every product under HKLM\...\Uninstall, in the 64-bit and the 32-bit view.
function Get-UninstallEntries {
    $list = @()
    foreach ($view in @([Microsoft.Win32.RegistryView]::Registry64, [Microsoft.Win32.RegistryView]::Registry32)) {
        $base = [Microsoft.Win32.RegistryKey]::OpenBaseKey([Microsoft.Win32.RegistryHive]::LocalMachine, $view)
        try {
            $root = $base.OpenSubKey('SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall')
            if ($null -eq $root) { continue }
            try {
                foreach ($name in $root.GetSubKeyNames()) {
                    $k = $root.OpenSubKey($name)
                    if ($null -eq $k) { continue }
                    try {
                        $list += New-Object PSObject -Property @{
                            View        = $view
                            Key         = $name
                            DisplayName = [string]$k.GetValue('DisplayName')
                            Quiet       = [string]$k.GetValue('QuietUninstallString')
                            Uninstall   = [string]$k.GetValue('UninstallString')
                            Msi         = ($k.GetValue('WindowsInstaller') -eq 1)
                        }
                    } finally { $k.Close() }
                }
            } finally { $root.Close() }
        } finally { $base.Close() }
    }
    return $list
}

# The entries an app owns: DisplayName starts with the manifest's
# displayNameMatch (ignoring case), the same rule the updater's inventory
# uses. The main product (shortest name) comes first.
function Find-AppEntries([string]$Match) {
    $m = $Match.Trim()
    return @(Get-UninstallEntries | Where-Object { $_.DisplayName.StartsWith($m, [StringComparison]::OrdinalIgnoreCase) } |
        Sort-Object -Property @{ Expression = { $_.DisplayName.Trim().Length } }, DisplayName)
}

function Test-EntryPresent($Entry) {
    return [bool](@(Get-UninstallEntries | Where-Object { $_.View -eq $Entry.View -and $_.Key -eq $Entry.Key }).Count)
}

# An uninstaller runs only if it is an existing .exe under Program Files.
function Test-AllowedExe([string]$Path) {
    if ($Path -notmatch '^[A-Za-z]:\\' -or $Path.Contains('"') -or -not $Path.EndsWith('.exe', [StringComparison]::OrdinalIgnoreCase)) {
        return $false
    }
    try { $full = [IO.Path]::GetFullPath($Path) } catch { return $false }
    $ok = $false
    foreach ($root in @($env:ProgramFiles, ${env:ProgramFiles(x86)}, $env:ProgramW6432)) {
        if (-not $root -or $root -notmatch '^[A-Za-z]:\\.') { continue }
        $r = [IO.Path]::GetFullPath($root).TrimEnd('\') + '\'
        if ($full.StartsWith($r, [StringComparison]::OrdinalIgnoreCase)) { $ok = $true }
    }
    return ($ok -and (Test-Path -LiteralPath $full -PathType Leaf))
}

# Splits an uninstall string into the program and the rest of its command
# line. A quoted program runs to the closing quote; an unquoted one is the
# shortest prefix ending in .exe that is an allowed, existing file (it may
# contain spaces). Returns $null when there is no allowed program.
function Split-UninstallString([string]$Line) {
    $s = $Line.TrimStart(' ', "`t")
    if ($s.StartsWith('"')) {
        $end = $s.IndexOf('"', 1)
        if ($end -lt 0) { return $null }
        $exe = $s.Substring(1, $end - 1)
        if (-not (Test-AllowedExe $exe)) { return $null }
        return @{ Exe = $exe; Tail = $s.Substring($end + 1).Trim() }
    }
    for ($i = 1; $i -le $s.Length; $i++) {
        if ($i -lt $s.Length -and $s[$i] -ne ' ' -and $s[$i] -ne "`t") { continue }
        if ($s[$i - 1] -eq ' ' -or $s[$i - 1] -eq "`t") { continue }
        $p = $s.Substring(0, $i)
        if (Test-AllowedExe $p) { return @{ Exe = $p; Tail = $s.Substring($i).Trim() } }
    }
    return $null
}

# Waits until the entry is gone (an NSIS uninstaller may hand over to a
# copy of itself and return early).
function Wait-EntryGone($Entry, [int]$Seconds) {
    $deadline = (Get-Date).AddSeconds($Seconds)
    while ((Get-Date) -lt $deadline) {
        if (-not (Test-EntryPresent $Entry)) { return $true }
        Start-Sleep -Seconds 3
    }
    return (-not (Test-EntryPresent $Entry))
}

function Uninstall-Entry($App, $Entry) {
    Write-Log ('uninstalling ' + $Entry.DisplayName + ' (' + $Entry.Key + ')')
    if ($Entry.Msi -and $Entry.Key -match '^\{[0-9A-Fa-f-]{36}\}$') {
        $deadline = (Get-Date).AddMinutes(10)
        do {
            $p = Start-Process -FilePath $msiexec -ArgumentList @('/x', $Entry.Key, '/qn', '/norestart') -Wait -PassThru -WindowStyle Hidden
            $code = $p.ExitCode
            if ($code -eq 1618) {
                Write-Log '  another installation is running; waiting'
                Start-Sleep -Seconds 30
            }
        } while ($code -eq 1618 -and (Get-Date) -lt $deadline)
        Write-Log ('  msiexec exit code ' + $code)
        if ($code -eq 3010 -or $code -eq 1641) { Write-Log '  a restart finishes the removal' }
    } else {
        $extra = @()
        if ($Entry.Quiet.Trim() -ne '') {
            $parts = Split-UninstallString $Entry.Quiet
        } elseif ($Entry.Uninstall.Trim() -ne '') {
            if (@($App.Args).Count -eq 0) {
                Write-Log '  no silent uninstall switch is known for it; skipped'
                return
            }
            $parts = Split-UninstallString $Entry.Uninstall
            $extra = @($App.Args)
        } else {
            Write-Log '  it has no uninstall command; skipped'
            return
        }
        if ($null -eq $parts) {
            Write-Log '  its uninstaller is not an existing .exe under Program Files; skipped'
            return
        }
        $argLine = ((@($parts.Tail) + $extra) | Where-Object { $_ -ne '' }) -join ' '
        $sp = @{ FilePath = $parts.Exe; Wait = $true; PassThru = $true; WindowStyle = 'Hidden' }
        if ($argLine -ne '') { $sp['ArgumentList'] = $argLine }
        $p = Start-Process @sp
        Write-Log ('  exit code ' + $p.ExitCode)
    }
    if (Wait-EntryGone $Entry 300) { Write-Log '  removed' } else { Write-Log '  still installed' }
}

# Deletes a file or folder tree without following junctions or symbolic
# links: a link is removed itself, never what it points to.
function Remove-Tree([string]$Path) {
    $item = Get-Item -LiteralPath $Path -Force
    if (-not $item.PSIsContainer) {
        Remove-Item -LiteralPath $Path -Force
        return
    }
    if (-not ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) {
        foreach ($c in @(Get-ChildItem -LiteralPath $Path -Force)) { Remove-Tree $c.FullName }
    }
    [IO.Directory]::Delete($Path)
}

function Remove-Folder([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) { return }
    try {
        Remove-Tree $Path
        Write-Log ('removed ' + $Path)
    } catch {
        Write-Log ('could not remove ' + $Path + ': ' + $_.Exception.Message)
    }
}

function Test-TaskPresent([string]$Name) {
    Invoke-Native $schtasks @('/Query', '/TN', $Name) -Quiet
    return ($script:NativeExit -eq 0)
}

Write-Log 'uninstall-officeapps: removing App Updater'

# 1. Scheduled tasks first, so no check starts while the apps go away.
foreach ($t in $Tasks) {
    if (-not (Test-TaskPresent $t)) { continue }
    Invoke-Native $schtasks @('/End', '/TN', $t) -Quiet
    Invoke-Native $schtasks @('/Delete', '/TN', $t, '/F')
}

# A check that is already running would keep installing; stop it.
try {
    $prefix = $programDir.TrimEnd('\') + '\'
    foreach ($p in @(Get-Process -Name 'appupdater' -ErrorAction SilentlyContinue)) {
        if ($p.Path -and $p.Path.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
            Write-Log ('stopping a running App Updater (process ' + $p.Id + ')')
            Stop-Process -Id $p.Id -Force
        }
    }
} catch {
    Write-Log ('could not stop App Updater: ' + $_.Exception.Message)
}

# 2. The apps.
if ($KeepApps) {
    Write-Log 'keeping the apps (-KeepApps)'
} else {
    foreach ($app in $Apps) {
        $entries = @(Find-AppEntries $app.Match)
        if ($entries.Count -eq 0) {
            Write-Log ($app.Name + ': not installed')
            continue
        }
        foreach ($e in $entries) {
            if (-not (Test-EntryPresent $e)) { continue }
            try {
                Uninstall-Entry $app $e
            } catch {
                Write-Log ('  failed: ' + $_.Exception.Message)
            }
        }
    }
}

# 3. The updater's folders (and any download folders a failed install left)
# and its Uninstall entry.
Remove-Folder $programDir
Remove-Folder $dataDir
foreach ($d in @(Get-ChildItem -LiteralPath $env:ProgramData -Directory -Force -ErrorAction SilentlyContinue)) {
    if ($d.Name -match '^AppUpdater-install-[0-9]{8}-[0-9]{6}-[0-9a-f]{8}$') { Remove-Folder $d.FullName }
}
try {
    $base = [Microsoft.Win32.RegistryKey]::OpenBaseKey([Microsoft.Win32.RegistryHive]::LocalMachine, [Microsoft.Win32.RegistryView]::Registry64)
    try {
        $k = $base.OpenSubKey($UpdaterKey)
        if ($null -ne $k) {
            $k.Close()
            $base.DeleteSubKeyTree($UpdaterKey)
            Write-Log ('removed HKLM\' + $UpdaterKey)
        }
    } finally { $base.Close() }
} catch {
    Write-Log ('could not remove HKLM\' + $UpdaterKey + ': ' + $_.Exception.Message)
}

# 4. Check what is left.
$left = @()
foreach ($t in $Tasks) { if (Test-TaskPresent $t) { $left += ('scheduled task ' + $t) } }
foreach ($d in @($programDir, $dataDir)) { if (Test-Path -LiteralPath $d) { $left += ('folder ' + $d) } }
$base = [Microsoft.Win32.RegistryKey]::OpenBaseKey([Microsoft.Win32.RegistryHive]::LocalMachine, [Microsoft.Win32.RegistryView]::Registry64)
try {
    $k = $base.OpenSubKey($UpdaterKey)
    if ($null -ne $k) { $k.Close(); $left += ('registry key HKLM\' + $UpdaterKey) }
} finally { $base.Close() }
if (-not $KeepApps) {
    foreach ($app in $Apps) {
        foreach ($e in @(Find-AppEntries $app.Match)) { $left += ($app.Name + ': ' + $e.DisplayName) }
    }
}

if ($left.Count -eq 0) {
    Write-Log 'done: everything was removed'
    exit 0
}
Write-Log 'done, but these are still there:'
foreach ($l in $left) { Write-Log ('  ' + $l) }
exit 1
