<#
install-officeapps.ps1: installs App Updater and, through it, the office apps.
Generated by updpublish. Run it as SYSTEM (RMM) or from an elevated Windows
PowerShell 5.1 or later. It never prompts.

The download URLs and SHA-256 of both updater builds are fixed in this file:
the script installs only the exact updater it was generated for.

  -Enroll a,b        app ids to keep updated (default: every app in the manifest)
  -SkipFirstCheck    set up only; the scheduled task installs the apps later

Exit codes: 0 every app ok or up to date; 1 an app or the first check had a
problem; 2 setup failed (or not elevated, or bad parameters); 3 download,
hash or architecture problem.
#>
[CmdletBinding()]
param(
    [string[]]$Enroll,
    [switch]$SkipFirstCheck
)

Set-StrictMode -Version 2
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$UpdaterVersion = '0.1.0-test.14'
$ManifestUrl = 'https://raw.githubusercontent.com/lifeguardcomputers/installers/office-apps-test/LG-OfficeApps/manifest.test.json'
$Channel = 'test'
$DefaultEnroll = @('pdf-reader', 'office-suite', 'photo-album')
$Builds = @{
    'x64'   = @{ Url = 'https://raw.githubusercontent.com/lifeguardcomputers/installers/office-apps-test/LG-OfficeApps/app-updater/0.1.0-test.14/appupdater-x64.exe'; Sha256 = '4867313f05ee95be525da17e105ff2d64cbf852393009899fd15bb0c1ece3b08' }
    'arm64' = @{ Url = 'https://raw.githubusercontent.com/lifeguardcomputers/installers/office-apps-test/LG-OfficeApps/app-updater/0.1.0-test.14/appupdater-arm64.exe'; Sha256 = '185c4a21c821362667bb44230abc42b463acdc5804017e7424abe689144e242c' }
}

$script:LogFile = $null

# Started from a PowerShell 7 window (or a tool running in one), this Windows
# PowerShell inherits PowerShell 7's module path and can load the wrong
# modules. Use the Windows PowerShell defaults; the updater and the apps'
# setup scripts it starts inherit them too.
$env:PSModulePath = (Join-Path $env:ProgramFiles 'WindowsPowerShell\Modules') + ';' + (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\Modules')

function Write-Log([string]$Message) {
    $line = (Get-Date).ToString('yyyy-MM-dd HH:mm:ss') + ' ' + $Message
    Write-Output $line
    if ($script:LogFile) {
        try { [IO.File]::AppendAllText($script:LogFile, $line + "`r`n", [Text.Encoding]::ASCII) } catch { }
    }
}

# Any error nothing else caught still ends up in the log, with exit code 2.
trap {
    Write-Log ('ERROR: ' + $_.Exception.Message + ' (line ' + $_.InvocationInfo.ScriptLineNumber + ')')
    exit 2
}

# Runs a program with an argument array (never a built command string),
# logs its output line by line and leaves its exit code in $script:NativeExit.
function Invoke-Native([string]$Exe, [string[]]$Arguments) {
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & $Exe @Arguments 2>&1 | ForEach-Object { Write-Log ('  ' + [string]$_) }
        $script:NativeExit = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $old
    }
}

# A 32-bit PowerShell (common for RMM agents) sees the 32-bit Program Files
# and registry; restart in the native 64-bit PowerShell.
if ([IntPtr]::Size -eq 4 -and $env:PROCESSOR_ARCHITEW6432) {
    $native = Join-Path $env:SystemRoot 'Sysnative\WindowsPowerShell\v1.0\powershell.exe'
    if ((Test-Path -LiteralPath $native) -and $PSCommandPath) {
        $fwd = @('-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', $PSCommandPath)
        if ($Enroll) { $fwd += @('-Enroll', ($Enroll -join ',')) }
        if ($SkipFirstCheck) { $fwd += '-SkipFirstCheck' }
        Write-Log 'restarting in 64-bit PowerShell'
        Invoke-Native $native $fwd
        exit $script:NativeExit
    }
}

[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12

Write-Log ('install-officeapps: App Updater ' + $UpdaterVersion + ', channel ' + $Channel)

$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Log 'ERROR: run this as SYSTEM or from an elevated PowerShell (Run as administrator).'
    exit 2
}

# Enroll list: -Enroll overrides the default; "a,b" works as well as a,b
# (powershell -File passes a comma list as one string).
$ids = @()
if ($Enroll) { $src = $Enroll } else { $src = $DefaultEnroll }
foreach ($item in $src) {
    foreach ($part in ([string]$item -split ',')) {
        $id = $part.Trim()
        if ($id -eq '') { continue }
        if ($id -cnotmatch '^[a-z0-9][a-z0-9-]*$') {
            Write-Log ('ERROR: "' + $id + '" is not an app id. Known ids: ' + ($DefaultEnroll -join ', '))
            exit 2
        }
        if ($ids -notcontains $id) { $ids += $id }
    }
}
if ($ids.Count -eq 0) {
    Write-Log 'ERROR: no apps to enroll.'
    exit 2
}
Write-Log ('apps: ' + ($ids -join ', '))

# Native architecture: an x64 PowerShell under emulation on ARM64 still
# reports ARM64 in PROCESSOR_ARCHITEW6432.
$arch = $env:PROCESSOR_ARCHITEW6432
if (-not $arch) { $arch = $env:PROCESSOR_ARCHITECTURE }
switch ($arch) {
    'ARM64' { $build = 'arm64' }
    'AMD64' { $build = 'x64' }
    default {
        Write-Log ('ERROR: unsupported processor architecture "' + $arch + '"; App Updater runs on 64-bit Windows (x64 or ARM64) only.')
        exit 3
    }
}
Write-Log ('architecture ' + $arch + ': using the ' + $build + ' build')

# A fresh folder that only SYSTEM and Administrators can use, created with
# that ACL (so no user can put a file in it first), then locked again with
# icacls as a check.
$stamp = (Get-Date).ToString('yyyyMMdd-HHmmss')
$work = Join-Path $env:ProgramData ('AppUpdater-install-' + $stamp + '-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
try {
    if (Test-Path -LiteralPath $work) { throw 'it already exists' }
    $sec = New-Object System.Security.AccessControl.DirectorySecurity
    $sec.SetSecurityDescriptorSddlForm('O:BAD:PAI(A;OICI;FA;;;SY)(A;OICI;FA;;;BA)')
    [void][IO.Directory]::CreateDirectory($work, $sec)
    $icacls = Join-Path $env:SystemRoot 'System32\icacls.exe'
    Invoke-Native $icacls @($work, '/inheritance:r', '/grant:r', '*S-1-5-18:(OI)(CI)F', '*S-1-5-32-544:(OI)(CI)F')
    if ($script:NativeExit -ne 0) { throw ('icacls exit code ' + $script:NativeExit) }
    if (@(Get-ChildItem -LiteralPath $work -Force).Count -ne 0) { throw 'the new folder is not empty' }
} catch {
    Write-Log ('ERROR: could not prepare the download folder ' + $work + ': ' + $_.Exception.Message)
    exit 3
}
$script:LogFile = Join-Path $work 'install.log'
Write-Log ('working folder ' + $work)

$exe = Join-Path $work ('appupdater-' + $build + '.exe')
$url = $Builds[$build].Url
$want = $Builds[$build].Sha256
$downloaded = $false
for ($try = 1; $try -le 3 -and -not $downloaded; $try++) {
    try {
        Write-Log ('downloading ' + $url + ' (try ' + $try + ')')
        Invoke-WebRequest -UseBasicParsing -Uri $url -OutFile $exe
        $downloaded = $true
    } catch {
        Write-Log ('download failed: ' + $_.Exception.Message)
        if ($try -lt 3) { Start-Sleep -Seconds (10 * $try) }
    }
}
if (-not $downloaded) {
    Write-Log ('ERROR: could not download the updater. The log is in ' + $script:LogFile)
    exit 3
}
$sha = [Security.Cryptography.SHA256]::Create()
$fs = [IO.File]::OpenRead($exe)
try { $got = [BitConverter]::ToString($sha.ComputeHash($fs)).Replace('-', '') } finally { $fs.Dispose(); $sha.Dispose() }
if ($got -ine $want) {
    Remove-Item -LiteralPath $exe -Force
    Write-Log ('ERROR: the downloaded updater has SHA-256 ' + $got.ToLowerInvariant() + ', expected ' + $want + '. Refusing to run it.')
    exit 3
}
Write-Log ('SHA-256 ok: ' + $want)

$setupArgs = @('setup', '--manifest-url', $ManifestUrl, '--channel', $Channel, '--enroll', ($ids -join ','))
Write-Log ('running: appupdater ' + ($setupArgs -join ' '))
Invoke-Native $exe $setupArgs
if ($script:NativeExit -ne 0) {
    Write-Log ('ERROR: setup failed with exit code ' + $script:NativeExit + '. The log is in ' + $script:LogFile)
    exit 2
}

# Setup made %ProgramData%\AppUpdater (admin-only): keep the install log there.
$dataDir = Join-Path $env:ProgramData 'AppUpdater'
$installed = Join-Path $env:ProgramFiles 'AppUpdater\appupdater.exe'
$finalLog = Join-Path $dataDir 'install.log'
try {
    [IO.File]::AppendAllText($finalLog, [IO.File]::ReadAllText($script:LogFile), [Text.Encoding]::ASCII)
    $script:LogFile = $finalLog
    Remove-Item -LiteralPath $work -Recurse -Force
} catch {
    Write-Log ('warning: could not move the install log: ' + $_.Exception.Message)
}

$code = 0
if ($SkipFirstCheck) {
    Write-Log 'skipping the first check (-SkipFirstCheck); the scheduled task installs the apps later'
} else {
    Write-Log 'running the first check (this installs the apps and can take a while)'
    Invoke-Native $installed @('check')
    $checkExit = $script:NativeExit
    if ($checkExit -ne 0) {
        Write-Log ('check failed with exit code ' + $checkExit)
        $code = 1
    }
    $lastResult = ''
    try {
        $st = Get-Content -Raw -LiteralPath (Join-Path $dataDir 'state.json') | ConvertFrom-Json
        if ($st.PSObject.Properties['lastResult']) { $lastResult = [string]$st.lastResult }
        if ($st.PSObject.Properties['apps'] -and $st.apps) {
            foreach ($p in $st.apps.PSObject.Properties) {
                $ok = $false
                if ($p.Value.PSObject.Properties['postInstallOk']) { $ok = [bool]$p.Value.postInstallOk }
                Write-Log ('  ' + $p.Name + ': postInstallOk=' + $ok)
            }
        }
    } catch {
        Write-Log ('could not read state.json: ' + $_.Exception.Message)
    }
    Write-Log ('check result: ' + $lastResult)
    if ($lastResult -ne 'ok') { $code = 1 }
}

Write-Log 'status:'
Invoke-Native $installed @('status')
if ($script:NativeExit -ne 0) { Write-Log ('status exit code ' + $script:NativeExit) }

if ($code -eq 0) {
    Write-Log 'done: App Updater is installed and every app is ok'
} else {
    Write-Log ('done with problems: see ' + (Join-Path $dataDir 'appupdater.log'))
}
exit $code
